"""Bake the overworld (whole-state map) data.

Reads the approved geography (read-only): island + islet outlines, both bridge footprints and the ferry
routes (island, islets and the Seberang Perai mainland), simplifies them for a phone and projects them into
overworld units. Zone hotspot art is cropped from the owner-approved Explore Penang atlases.

    python3 tools/bake_overworld.py [path to explore-penang repo]   # repo only needed to re-crop art
"""
import json, math, os, sys
import numpy as np
from PIL import Image
from skimage.measure import approximate_polygon

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EP = sys.argv[1] if len(sys.argv) > 1 else None
geo = json.load(open(f'{ROOT}/data/geography/geography.geojson'))

# same base projection as the zones (tools/bake_zone.py), scaled for the whole state
B = [100.16, 5.20, 100.52, 5.51]; COS = math.cos(5.36 * math.pi / 180)
U = min(960 / ((B[2] - B[0]) * COS), 740 / (B[3] - B[1])); SCALE = 2.6
def P(lon, lat):
    x = 70 + (lon - B[0]) * COS * U; y = 70 + (B[3] - lat) * U
    return [round((x + .16 * (y - 440)) * SCALE, 1), round((100 + .76 * y) * SCALE, 1)]

def simp(ring, tol):
    pts = np.array([P(*c) for c in ring]); s = approximate_polygon(pts, tolerance=tol)
    return s.round(1).tolist()

land, bridges, ferries = [], [], []
for f in geo['features']:
    g = f['geometry']
    if g['type'] == 'MultiPolygon':
        for poly in g['coordinates']:
            ring = simp(poly[0], 1.6)
            a_ = np.array(ring); area = .5 * abs(np.dot(a_[:, 0], np.roll(a_[:, 1], 1)) - np.dot(a_[:, 1], np.roll(a_[:, 0], 1)))
            if len(ring) >= 4 and area > 60: land.append(ring)
    elif g['type'] == 'Polygon':
        bridges.append(simp(g['coordinates'][0], .8))
    elif g['type'] == 'LineString':
        ferries.append([P(*c) for c in g['coordinates']])
land.sort(key=len, reverse=True)

# the state relation and the island relation overlap: drop rings whose bounding box duplicates a larger one
def bbox(r): a_ = np.array(r); return np.r_[a_.min(0), a_.max(0)]
uniq = []
for r in land:
    if not any(np.abs(bbox(r) - bbox(u)).max() < 25 for u in uniq): uniq.append(r)
land = uniq

# hotspot anchors are interpretive (spread apart so the art does not overlap); stations keep real coordinates
ZONES = [
    dict(id='george-town', at=(100.336, 5.416), art=('d', 2, 0), arrive='bus', status='open'),
    dict(id='air-itam', at=(100.285, 5.392), art=('d', 1, 0), arrive='bus', status='open'),
    dict(id='penang-hill', at=(100.249, 5.429), art=('d', 0, 0), arrive='funicular', status='open', via='air-itam'),
    dict(id='north', at=(100.262, 5.470), art=('d', 0, 2), arrive='bus', status='soon'),
    dict(id='south', at=(100.232, 5.345), art=('h', 1, 1), arrive='bus', status='soon'),
    dict(id='butterworth', at=(100.395, 5.405), art=('h', 2, 1), arrive='ferry', status='open'),
]
NAMES = {'george-town': ('George Town', 'George Town'), 'air-itam': ('Air Itam', 'Air Itam'), 'penang-hill': ('Bukit Bendera', 'Penang Hill'),
         'north': ('Gurney & pantai utara', 'Gurney & north coast'), 'south': ('Balik Pulau & selatan', 'Balik Pulau & the south'),
         'butterworth': ('Seberang Perai', 'Seberang Perai (mainland)')}
out_z = []
for z in ZONES:
    out_z.append({'id': z['id'], 'name': {'bm': NAMES[z['id']][0], 'en': NAMES[z['id']][1]}, 'at': P(*z['at']), 'lonlat': list(z['at']),
                  'arrive': z['arrive'], 'status': z['status'], **({'via': z['via']} if 'via' in z else {})})

xs = [p[0] for r in land for p in r]; ys = [p[1] for r in land for p in r]
data = {'_note': 'Generated by tools/bake_overworld.py from the approved geography (read-only).',
        'scale': SCALE, 'bounds': [min(xs), min(ys), max(xs), max(ys)], 'land': land,
        'bridges': bridges, 'ferries': ferries, 'zones': out_z, 'unlock': {'zone': 'george-town', 'stamps': 6}}
json.dump(data, open(f'{ROOT}/content/overworld.json', 'w'), separators=(',', ':'))
print('land rings', [len(r) for r in land][:6], 'bridges', len(bridges), 'ferries', len(ferries), 'bounds', data['bounds'])

if EP:  # crop zone art (owner-approved Explore Penang atlases), 256px
    os.makedirs(f'{ROOT}/public/overworld', exist_ok=True)
    atl = {'d': Image.open(f'{EP}/review/assets/diorama-atlas-v3.webp').convert('RGBA'), 'h': Image.open(f'{EP}/review/assets/hotspot-atlas-v1.webp').convert('RGBA')}
    for z in ZONES:
        a, cx, cy = z['art']; im = atl[a]; c = 384
        cell = im.crop((cx * c, cy * c, cx * c + c, cy * c + c)); cell = cell.crop(cell.getbbox())
        k = 256 / max(cell.size); cell = cell.resize((round(cell.width * k), round(cell.height * k)), Image.LANCZOS)
        cell.save(f'{ROOT}/public/overworld/{z["id"]}.webp', quality=86, method=6)
    print('art written')
